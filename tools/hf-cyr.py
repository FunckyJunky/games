s=open(__import__('os').path.join(__import__('os').path.dirname(__file__),'..','public','thuisfront','dev','render.js')).read()
F=bytes.fromhex(re.search(r"const FONT_HEX = '([0-9a-f]+)'",s).group(1))
def basic(ch): return list(F[(ord(ch)-32)*8:(ord(ch)-32)*8+8])
def enc(rows):
    assert len(rows)==7, rows
    out=[]
    for r in rows:
        r=r.ljust(8,'.'); assert len(r)==8, r
        out.append(sum(1<<i for i,c in enumerate(r) if c=='#'))
    return out+[0]
